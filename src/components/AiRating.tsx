import { useState } from 'react';
import { Link } from 'react-router-dom';
import { AI_MODEL, rateProperty } from '../lib/ai';
import { aiKey, setState, useStore } from '../lib/store';
import { Meter, Section } from './detail';
import { Icon } from './ui';

const LEVELS = ['Very Low', 'Low', 'Medium', 'High', 'Very High'];

// AI deal rating for any record key. `facts` gathers everything known about the record
// at the moment the button is pressed; the result is kept so it is not billed twice.
export function AiRating({ id, facts, note, loading }: { id: string; facts: () => unknown | Promise<unknown>; note?: string; loading?: boolean }) {
  const { ratings } = useStore();
  const r = ratings[id];
  const key = aiKey();
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  const run = async () => {
    setBusy(true);
    setError('');
    try {
      const rating = await rateProperty(await facts(), key);
      setState((s) => ({ ratings: { ...s.ratings, [id]: rating } }));
    } catch (e) {
      setError(e instanceof Error ? e.message : 'The rating could not be generated.');
    }
    setBusy(false);
  };

  return (
    <Section
      title="AI Deal Rating"
      aside={key && <button className="btn sm violet no-print" disabled={busy || loading} onClick={run}><Icon name="spark" size={14} /> {busy ? 'Rating…' : loading ? 'Loading record…' : r ? 'Re-rate' : 'Generate Rating'}</button>}
    >
      {!key && <p className="muted">Add an Anthropic API key under <Link to="/account">Account</Link> to have Claude rate this property from every fact on the record.</p>}
      {error && <p className="error" role="alert">{error}</p>}
      {key && !r && !error && <p className="muted">Sends the facts on this record (no owner names or contact details) to Claude ({AI_MODEL}) and returns a 0–100 rating with its reasons. Each rating is one small API request.</p>}
      {r && (
        <>
          <div className="ai-head">
            <div className="ai-score" role="img" aria-label={`Score ${r.score} out of 100, grade ${r.grade}`}><b>{r.score}</b><span>/ 100 · {r.grade}</span></div>
            <p className="grow">{r.verdict}</p>
          </div>
          <div className="intel-row">
            <Meter title="Opportunity" label={LEVELS[r.opportunity - 1]} level={r.opportunity} />
            <Meter title="Seller motivation" label={LEVELS[r.motivation - 1]} level={r.motivation} />
            <Meter title="Buyer risk" label={LEVELS[r.risk - 1]} level={r.risk} />
            <div className="meter"><span>Confidence</span><b>{r.confidence}</b></div>
          </div>
          <div className="ai-cols">
            <div><h4>In favour</h4><ul className="reasons">{r.strengths.map((t) => <li key={t}>{t}</li>)}</ul></div>
            <div><h4>Against</h4><ul className="reasons">{r.risks.map((t) => <li key={t}>{t}</li>)}</ul></div>
            <div><h4>Missing facts</h4><ul className="reasons">{r.missing.length ? r.missing.map((t) => <li key={t}>{t}</li>) : <li>None noted</li>}</ul></div>
          </div>
          <p><b>Suggested strategy:</b> {r.strategy}</p>
          <p className="muted">Generated by {r.model} on {new Date(r.at).toLocaleString()} from the data shown on this page{note ? `. ${note}` : ''}. An opinion to check, not an appraisal or financial advice.</p>
        </>
      )}
    </Section>
  );
}
